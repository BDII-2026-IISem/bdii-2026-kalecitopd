-- ============================================================
-- ESQUEMA DDL - ODONTONOVA (ORACLE DATABASE)
-- ============================================================

DROP TABLE pagos CASCADE CONSTRAINTS;
DROP TABLE sesiones_clinicas CASCADE CONSTRAINTS;
DROP TABLE detalles_tratamiento CASCADE CONSTRAINTS;
DROP TABLE procedimientos CASCADE CONSTRAINTS;
DROP TABLE planes_tratamiento CASCADE CONSTRAINTS;
DROP TABLE citas CASCADE CONSTRAINTS;
DROP TABLE historias_clinicas CASCADE CONSTRAINTS;
DROP TABLE sillones CASCADE CONSTRAINTS;
DROP TABLE odontologos CASCADE CONSTRAINTS;
DROP TABLE pacientes CASCADE CONSTRAINTS;

-- 1. Pacientes
CREATE TABLE pacientes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR2(20) NOT NULL,
    numero_documento VARCHAR2(50) NOT NULL UNIQUE,
    nombre VARCHAR2(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Odontólogos
CREATE TABLE odontologos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    especialidad VARCHAR2(100) NOT NULL,
    telefono VARCHAR2(20),
    email VARCHAR2(100) NOT NULL UNIQUE,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Sillones
CREATE TABLE sillones (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(20) NOT NULL UNIQUE,
    estado VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Historias Clínicas
CREATE TABLE historias_clinicas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id NUMBER NOT NULL UNIQUE REFERENCES pacientes(id) ON DELETE CASCADE,
    antecedentes CLOB,
    alergias VARCHAR2(255),
    grupo_sanguineo VARCHAR2(10),
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. Citas
CREATE TABLE citas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id NUMBER NOT NULL REFERENCES pacientes(id) ON DELETE CASCADE,
    odontologo_id NUMBER NOT NULL REFERENCES odontologos(id) ON DELETE CASCADE,
    sillon_id NUMBER REFERENCES sillones(id) ON DELETE SET NULL,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    motivo CLOB,
    estado VARCHAR2(50) DEFAULT 'PENDIENTE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. Planes de Tratamiento
CREATE TABLE planes_tratamiento (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id NUMBER NOT NULL REFERENCES pacientes(id) ON DELETE CASCADE,
    nombre VARCHAR2(150) NOT NULL,
    descripcion CLOB,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 7. Procedimientos
CREATE TABLE procedimientos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(150) NOT NULL,
    descripcion CLOB,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. Detalles de Tratamiento
CREATE TABLE detalles_tratamiento (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabecera_id NUMBER NOT NULL REFERENCES planes_tratamiento(id) ON DELETE CASCADE,
    item_id NUMBER NOT NULL REFERENCES procedimientos(id) ON DELETE CASCADE,
    cantidad NUMBER DEFAULT 1 NOT NULL,
    valor_unitario NUMBER(10, 2) NOT NULL,
    total NUMBER(10, 2) NOT NULL,
    observacion CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. Sesiones Clínicas
CREATE TABLE sesiones_clinicas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia_id NUMBER UNIQUE REFERENCES citas(id) ON DELETE CASCADE,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    total NUMBER(10, 2) NOT NULL,
    estado VARCHAR2(50) DEFAULT 'EN_PROCESO',
    observaciones CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 10. Pagos
CREATE TABLE pagos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia_tipo VARCHAR2(50) DEFAULT 'PLAN_TRATAMIENTO',
    referencia_id NUMBER NOT NULL REFERENCES planes_tratamiento(id) ON DELETE CASCADE,
    metodo VARCHAR2(50) NOT NULL,
    monto NUMBER(10, 2) NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR2(50) DEFAULT 'COMPLETADO',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
